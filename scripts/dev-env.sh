#!/usr/bin/env bash
# Creates .env for local development with freshly generated secrets.
#
#   ADMIN_EMAIL=you@example.com ADMIN_CAMPUS_SLUG=lpu scripts/dev-env.sh
#
# Nothing secret is stored in the repository: docker-compose.yml reads every
# credential from .env (git-ignored) and refuses to start when one is missing.
# Re-running keeps an existing .env unless FORCE=1 is set.
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -f .env && "${FORCE:-0}" != "1" ]]; then
  echo ".env already exists; set FORCE=1 to regenerate it" >&2
  exit 1
fi
: "${ADMIN_EMAIL:?set ADMIN_EMAIL to the email of the first admin account}"
: "${ADMIN_CAMPUS_SLUG:?set ADMIN_CAMPUS_SLUG to the slug of the campus the admin belongs to (see /campuses)}"

secret() { openssl rand -hex "${1:-32}"; }
admin_password="$(secret 12)"

umask 077
cat > .env <<ENV
# Generated by scripts/dev-env.sh on $(date -u +%Y-%m-%d). Local development only; never commit.
POSTGRES_PASSWORD=$(secret 24)
JWT_SECRET=$(secret 32)
INTERNAL_TOKEN=$(secret 32)
FILE_SIGNING_SECRET=$(secret 32)
LIVEKIT_API_KEY=API$(secret 6)
LIVEKIT_API_SECRET=$(secret 32)

ADMIN_EMAIL=${ADMIN_EMAIL}
ADMIN_PASSWORD=${admin_password}
ADMIN_CAMPUS_SLUG=${ADMIN_CAMPUS_SLUG}

APP_URL=http://localhost:5190
MAIL_FROM="Your Mate <no-reply@localhost>"
STAFF_EMAIL=${STAFF_EMAIL:-}
DEV_MODE=true
DEBUG=false
ENV

echo "Wrote .env. The admin account ${ADMIN_EMAIL} is created on first start with the password in .env (ADMIN_PASSWORD)."
