#!/usr/bin/env bash
# Creates .env for a production server with fresh random secrets.
#
#   APP_DOMAIN=yourmate.duckdns.org ACME_EMAIL=you@gmail.com \
#   ADMIN_EMAIL=you@gmail.com ADMIN_CAMPUS_SLUG=lpu deploy/make-env.sh
#
# Optional: SMTP_USERNAME and SMTP_PASSWORD (a Gmail address and App
# Password) to send real email; without them, emails are only logged.
# Refuses to overwrite an existing .env unless FORCE=1.
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -f .env && "${FORCE:-0}" != "1" ]]; then
  echo ".env already exists; set FORCE=1 to replace it (this changes every secret)" >&2
  exit 1
fi
: "${APP_DOMAIN:?set APP_DOMAIN, e.g. yourmate.duckdns.org}"
: "${ACME_EMAIL:?set ACME_EMAIL to a real inbox for certificate notices}"
: "${ADMIN_EMAIL:?set ADMIN_EMAIL to the email of the first admin account}"
: "${ADMIN_CAMPUS_SLUG:?set ADMIN_CAMPUS_SLUG, e.g. lpu}"

secret() { openssl rand -hex "${1:-32}"; }
# The server's public address, which the video server announces to browsers.
public_ip="${LIVEKIT_NODE_IP:-$(curl -fsS --max-time 5 https://checkip.amazonaws.com || true)}"
if [[ -z "$public_ip" ]]; then
  echo "could not detect the public IP; set LIVEKIT_NODE_IP" >&2
  exit 1
fi
admin_password="$(secret 12)"
smtp_from="${SMTP_USERNAME:-no-reply@${APP_DOMAIN}}"

umask 077
cat > .env <<ENV
# Generated by deploy/make-env.sh on $(date -u +%Y-%m-%d). Production. Never commit.
APP_DOMAIN=${APP_DOMAIN}
ACME_EMAIL=${ACME_EMAIL}
APP_URL=https://${APP_DOMAIN}
DEV_MODE=false
DEBUG=false

POSTGRES_PASSWORD=$(secret 24)
JWT_SECRET=$(secret 32)
INTERNAL_TOKEN=$(secret 32)
FILE_SIGNING_SECRET=$(secret 32)
LIVEKIT_API_KEY=API$(secret 6)
LIVEKIT_API_SECRET=$(secret 32)
LIVEKIT_NODE_IP=${public_ip}

ADMIN_EMAIL=${ADMIN_EMAIL}
ADMIN_PASSWORD=${admin_password}
ADMIN_CAMPUS_SLUG=${ADMIN_CAMPUS_SLUG}
STAFF_EMAIL=${STAFF_EMAIL:-}

MAIL_FROM="Your Mate <${smtp_from}>"
ENV

if [[ -n "${SMTP_USERNAME:-}" ]]; then
  cat >> .env <<ENV
SMTP_HOST=${SMTP_HOST:-smtp.gmail.com}
SMTP_PORT=${SMTP_PORT:-587}
SMTP_USERNAME=${SMTP_USERNAME}
SMTP_PASSWORD=${SMTP_PASSWORD:?set SMTP_PASSWORD with SMTP_USERNAME}
ENV
else
  echo "note: no SMTP_USERNAME given; emails (signup codes!) will only be logged until you add SMTP_* to .env" >&2
fi

echo "Wrote .env for https://${APP_DOMAIN} (video server address ${public_ip})."
echo "Admin login: ${ADMIN_EMAIL} with the ADMIN_PASSWORD in .env."
